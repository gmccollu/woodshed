// The UI's mock (web/src/lib/mock/setup.ts) answers the setup routes from
// web/src/lib/mock/setup-fixture.json: the families, and every family, data
// type and transport's snippet with the default choices, for the mock
// server's identity. This test keeps that file equal to what the templates
// generate (go test ./internal/setuphelper -update rewrites it).
func TestMockFixture(t *testing.T) {
	srv := Server{
		HostIPs:   []string{"10.1.0.50", "192.168.64.1", "fd00::50"},
		Names:     []string{"logs-01", "logs-01.example.net"},
		TLSNames:  []string{"localhost", "logs-01", "logs-01.example.net"},
		TLSSource: "woodshed",
		CASHA256:  "3F:9A:1C:07:5B:E2:44:D0:8C:61:2F:A9:73:0E:B5:16:C8:4D:92:E7:01:6B:3A:F5:58:C3:9E:20:7D:B4:4A:11",
		UDP:       Listener{Enabled: true, Addr: "0.0.0.0", Port: 514},
		TCP:       Listener{Enabled: true, Addr: "0.0.0.0", Port: 514},
		TLS:       Listener{Enabled: true, Addr: "0.0.0.0", Port: 6514},
		Trap:      Listener{Enabled: true, Addr: "0.0.0.0", Port: 162},
		Flow:      &FlowListener{Enabled: true, Addr: "0.0.0.0", FlowPort: 2055, IPFIXPort: 4739},
	}
	// The mock validates a request as Generate does (the patterns and choice
	// lists below), then serves the snippet rendered for the same kind of
	// address, an IPv4 one, an IPv6 one or a host name, with the sample
	// address swapped for the requested one: so an IPv6 address gets its
	// brackets and rocommunity6, and a name its placeholders, as from the server.
	type choices struct {
		Severities []string `json:"severities"`
		Facilities []string `json:"facilities"`
		Auths      []string `json:"auths"`
		Privs      []string `json:"privs"`
	}
	fx := struct {
		Note     string                        `json:"note"`
		Families []Family                      `json:"families"`
		Patterns map[string]string             `json:"patterns"`
		Choices  choices                       `json:"choices"`
		Samples  map[string]string             `json:"samples"`
		Snippets map[string]map[string]Snippet `json:"snippets"`
		Parity   []parityCase                  `json:"parity"`
	}{
		Note:     "Generated by internal/setuphelper's TestMockFixture (go test ./internal/setuphelper -update); don't edit.",
		Families: Families(),
		Patterns: Patterns(),
		Choices:  choices{Severities(), Facilities(), AuthChoices(), PrivChoices()},
		Samples:  map[string]string{"ipv4": "10.1.0.50", "ipv6": "fd00::50", "name": "logs-01.example.net"},
		Snippets: map[string]map[string]Snippet{},
	}
	for _, f := range fx.Families {
		for _, w := range f.What {
			for _, tr := range f.Transports[w] {
				key := f.ID + "/" + w + "/" + tr
				fx.Snippets[key] = map[string]Snippet{}
				for kind, addr := range fx.Samples {
					s, err := Generate(srv, Request{Family: f.ID, What: w, Transport: tr, Address: addr})
					if err != nil {
						t.Fatal(err)
					}
					if kind == "ipv4" {
						// The default request (no address) is the IPv4 one.
						d, _ := Generate(srv, Request{Family: f.ID, What: w, Transport: tr})
						if d.Address != addr {
							t.Fatalf("the default address is %s, not the IPv4 sample %s", d.Address, addr)
						}
					}
					fx.Snippets[key][kind] = s
				}
			}
		}
	}
	// The mock's own checks are tested against these (web/src/lib/mock/setupcore.test.ts).
	for _, body := range parityRequests() {
		var r Request
		raw, _ := json.Marshal(body)
		if err := json.Unmarshal(raw, &r); err != nil {
			t.Fatal(err)
		}
		pc := parityCase{Body: body}
		s, err := Generate(srv, r)
		var e *Error
		switch {
		case errors.As(err, &e):
			pc.Field = e.Field
		case err != nil:
			t.Fatal(err)
		default:
			pc.Address = s.Address
		}
		fx.Parity = append(fx.Parity, pc)
	}
	b, err := json.MarshalIndent(fx, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	b = append(b, '\n')
	path := filepath.Join("..", "..", "web", "src", "lib", "mock", "setup-fixture.json")
	if *update {
		if err := os.WriteFile(path, b, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(got), "\r\n", "\n") != string(b) {
		t.Errorf("%s is stale: run go test ./internal/setuphelper -update", path)
	}
}

type parityCase struct {
	Body    map[string]any `json:"body"`
	Field   string         `json:"field"`
	Address string         `json:"address"`
}

