package setuphelper

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The UI's mock (web/src/lib/mock/setup.ts) answers the setup routes from
// web/src/lib/mock/setup-fixture.json: the families, and every family, data
// type and transport's snippet with the default choices, for the mock
// server's identity. This test keeps that file equal to what the templates
// generate (go test ./internal/setuphelper -update rewrites it).
func TestMockFixture(t *testing.T) {
	srv := Server{
		HostIPs:   []string{"10.1.0.50", "192.168.64.1", "fd00::50"},
		Names:     []string{"logs-01", "logs-01.example.net"},
		TLSNames:  []string{"localhost", "logs-01", "logs-01.example.net"},
		TLSSource: "woodshed",
		CASHA256:  "3F:9A:1C:07:5B:E2:44:D0:8C:61:2F:A9:73:0E:B5:16:C8:4D:92:E7:01:6B:3A:F5:58:C3:9E:20:7D:B4:4A:11",
		UDP:       Listener{Enabled: true, Addr: "0.0.0.0", Port: 514},
		TCP:       Listener{Enabled: true, Addr: "0.0.0.0", Port: 514},
		TLS:       Listener{Enabled: true, Addr: "0.0.0.0", Port: 6514},
		Trap:      Listener{Enabled: true, Addr: "0.0.0.0", Port: 162},
	}
	fx := struct {
		Note     string             `json:"note"`
		Families []Family           `json:"families"`
		Snippets map[string]Snippet `json:"snippets"`
	}{
		Note:     "Generated by internal/setuphelper's TestMockFixture (go test ./internal/setuphelper -update); don't edit.",
		Families: Families(),
		Snippets: map[string]Snippet{},
	}
	for _, f := range fx.Families {
		for _, w := range f.What {
			for _, tr := range f.Transports[w] {
				s, err := Generate(srv, Request{Family: f.ID, What: w, Transport: tr})
				if err != nil {
					t.Fatal(err)
				}
				fx.Snippets[f.ID+"/"+w+"/"+tr] = s
			}
		}
	}
	b, err := json.MarshalIndent(fx, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	b = append(b, '\n')
	path := filepath.Join("..", "..", "web", "src", "lib", "mock", "setup-fixture.json")
	if *update {
		if err := os.WriteFile(path, b, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(got), "\r\n", "\n") != string(b) {
		t.Errorf("%s is stale: run go test ./internal/setuphelper -update", path)
	}
}
